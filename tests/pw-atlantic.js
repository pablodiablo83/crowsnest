// Atlantic weather chart (/atlantic.html): loads the bundled snapshot, draws, zooms, drags, picks a zone. Usage: node tests/pw-atlantic.js [screenshot dir]
const { chromium } = require('playwright');
const B = process.env.BASE || 'http://localhost:8091', OUT = process.argv[2] || '/tmp';
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const sid = await require('./lib/session')(B);
  const br = await chromium.launch({ executablePath: process.env.CHROME || undefined });
  const ctx = await br.newContext({ viewport: { width: 1000, height: 700 } });
  await ctx.addCookies([{ name: 'cn_sid', value: sid, url: B }]);
  const pg = await ctx.newPage(); const errs = [];
  pg.on('pageerror', e => errs.push(String(e)));
  pg.on('console', m => { if (m.type() === 'error' && !/font|fonts\.g|net::ERR|Failed to load resource/i.test(m.text())) errs.push(m.text()); });
  // the snapshot ages: pin "now" to 6 h after it was fetched so the list view always has a future
  const wx = await (await fetch(B + '/atlantic/wx.json')).json();
  const NOW = Date.parse(wx.fetched.replace(/Z$/, ':00Z')) + 6 * 3600e3;
  await ctx.addInitScript(n => { window.__NOW = n; }, NOW);
  await pg.goto(B + '/atlantic.html'); await pg.waitForSelector('#msg', { state: 'detached', timeout: 15000 });
  ok(errs.length === 0, 'no page errors ' + errs.join('|'));
  // ---- option A: the page opens on "Now and ahead" ----
  ok(await pg.locator('#ahead').isVisible(), 'opens on the Now and ahead list');
  ok(/No position yet/.test(await pg.locator('#ahead').innerText()), 'no position: says so plainly');
  await pg.evaluate(() => localStorage.setItem('arcwx_boat', JSON.stringify([17.19, -52.43])));
  await pg.reload(); await pg.waitForSelector('#ahead .ah-now', { timeout: 15000 });
  let txt = await pg.locator('#ahead').innerText();
  ok(/NOW · YOUR POSITION/.test(txt) && /17°11′N 052°26′W/.test(txt), 'now card at the boat position (' + txt.split('\n').slice(1, 4).join(' / ') + ')');
  ok(/F\d+/.test(await pg.locator('.ah-bfbig').innerText()) && /gusts \d+ kn/.test(txt), 'force, wind and gusts shown');
  const rows = await pg.locator('.ah-row').count();
  ok(rows >= 5 && /Arrive/.test(txt), rows + ' rows every 12 h, ending with Arrive');
  ok(/to Rodney Bay/.test(txt) && /6\.5 kn/.test(txt), 'distance to the finish at 6.5 kn');
  const p = await pg.evaluate(() => CNAhead._plan());
  ok(p.rows.every((r, i) => !i || r.nm > p.rows[i - 1].nm || r.arrived), 'positions advance along the route');
  await pg.click('#ahFast'); await pg.click('#ahFast');
  ok(/7\.5 kn/.test(await pg.locator('#ahKn').innerText()) && await pg.locator('.ah-row').count() < rows, 'faster: fewer rows to arrival');
  ok(await pg.evaluate(() => JSON.parse(localStorage.getItem('arcwx_speed'))) === 7.5, 'speed remembered');
  // phone width: nothing wider than the screen
  await pg.setViewportSize({ width: 375, height: 812 }); await pg.waitForTimeout(200);
  ok(await pg.evaluate(() => { const a = document.getElementById('ahead'); return a.scrollWidth <= a.clientWidth + 1 && [...a.querySelectorAll('.ah-row, .ah-now')].every(e => e.getBoundingClientRect().right <= innerWidth + 1); }), 'list fits a 375 pt phone');
  await pg.screenshot({ path: OUT + '/atlantic-ahead.png', fullPage: false });
  await pg.click('#ahNight'); ok(await pg.evaluate(() => document.body.classList.contains('night')), 'Night from the list'); await pg.click('#ahNight');
  await pg.setViewportSize({ width: 1000, height: 700 }); await pg.waitForTimeout(200);
  await pg.click('#ahChart'); await pg.waitForTimeout(400);
  ok(!(await pg.locator('#ahead').isVisible()), 'Show on chart opens the chart');
  const lit = async () => pg.evaluate(() => { const c = document.querySelector('.amap-pane canvas'); const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let n = 0; for (let i = 3; i < d.length; i += 4 * 97) if (d[i] > 0) n++; return n; });
  ok(await lit() > 200, 'weather canvas has pixels');
  ok(await pg.locator('.amap-root svg rect').count() === 23, '23 zone boxes drawn'); ok(await pg.locator('.amap-root svg path').count() >= 1, 'route drawn');
  ok(await pg.locator('.zlab').count() === 23, '23 zone labels');
  const z0 = await pg.evaluate(() => 0 + window.__z0 || 0);
  await pg.click('#zIn'); await pg.waitForTimeout(700); ok(await lit() > 200, 'still drawn after zoom in');
  const box = await pg.locator('#map').boundingBox();
  await pg.mouse.move(box.x + 500, box.y + 300); await pg.mouse.down(); await pg.mouse.move(box.x + 380, box.y + 260, { steps: 6 }); await pg.mouse.up(); await pg.waitForTimeout(600);
  ok(await lit() > 200, 'still drawn after drag');
  await pg.click('#zFit'); await pg.waitForTimeout(900);
  await pg.mouse.click(box.x + box.width / 2, box.y + box.height / 2); await pg.waitForTimeout(300);
  ok(/Zone|zone|[A-W]{2}/.test(await pg.locator('#side').innerText()), 'side panel shows a zone after a click');
  await pg.click('#layers button[data-l=sea]'); await pg.waitForTimeout(300); ok(await lit() > 100, 'sea layer draws');
  await pg.screenshot({ path: OUT + '/atlantic.png' });
  await pg.click('#bAhead'); ok(await pg.locator('#ahead').isVisible(), 'chart button returns to the list');
  ok(errs.length === 0, 'no page errors at end ' + errs.join('|'));
  await br.close(); process.exit(fails ? 1 : 0);
})();
